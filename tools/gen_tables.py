#!/usr/bin/env python3
"""Generate crates/hakoniwa-core/src/tables.rs from the Perl R.A. configuration.

Usage: tools/gen-tables.sh  (wraps this script; see that file)

Inputs:
  argv[1]  config.json  -- produced by tools/dump-perl-config.pl (values as Perl sees them)
  argv[2]  hako-main.cgi converted to UTF-8 (used only for the `# comment` after each constant)
Output: Rust source on stdout.
"""
import json
import re
import sys


def rust_str(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    cfg = json.load(open(sys.argv[1], encoding="utf-8"))
    src = open(sys.argv[2], encoding="utf-8").read().splitlines()

    comments = {}
    for line in src:
        m = re.match(r"^\$(H(?:land|com)\w+)\s*=\s*[0-9]+;\s*(?:#\s*(.*))?$", line)
        if m:
            comments[m.group(1)] = (m.group(2) or "").strip()

    out = []
    w = out.append
    w("// @generated by tools/gen_tables.py from hako-r-a_FE/hako-main.cgi. Do not edit by hand.")
    w("//! Static game tables ported verbatim from the Perl configuration section.")
    w("")
    w("#![allow(clippy::upper_case_acronyms)]")
    w("")

    # ---- land kinds -------------------------------------------------------
    lands = sorted(
        ((k[len("$Hland"):], v) for k, v in cfg.items() if k.startswith("$Hland")),
        key=lambda kv: kv[1],
    )
    w("/// 地形番号 (`$HlandXxx`)。セーブデータには数値のまま保存される。")
    w("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    w("#[repr(u8)]")
    w("pub enum LandKind {")
    for name, v in lands:
        c = comments.get("Hland" + name, "")
        if c:
            w(f"    /// {c}")
        w(f"    {name} = {v},")
    w("}")
    w("")
    w("impl LandKind {")
    w(f"    pub const ALL: [LandKind; {len(lands)}] = [")
    for name, _ in lands:
        w(f"        LandKind::{name},")
    w("    ];")
    w("")
    w("    pub fn from_u8(v: u8) -> Option<Self> {")
    w("        Self::ALL.iter().copied().find(|k| *k as u8 == v)")
    w("    }")
    w("}")
    w("")

    # ---- command kinds ----------------------------------------------------
    names = cfg["@HcomName"]
    costs = cfg["@HcomCost"]
    coms = sorted(
        (
            (k[len("$Hcom"):], v)
            for k, v in cfg.items()
            if k.startswith("$Hcom") and k not in ("$HcommandMax", "$HcommandTotal")
        ),
        key=lambda kv: kv[1],
    )
    w("/// 計画番号 (`$HcomXxx`)。")
    w("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    w("#[repr(u16)]")
    w("pub enum CommandKind {")
    for name, v in coms:
        c = comments.get("Hcom" + name, "")
        if c:
            w(f"    /// {c}")
        w(f"    {name} = {v},")
    w("}")
    w("")
    w("impl CommandKind {")
    w(f"    pub const ALL: [CommandKind; {len(coms)}] = [")
    for name, _ in coms:
        w(f"        CommandKind::{name},")
    w("    ];")
    w("")
    w("    pub fn from_u16(v: u16) -> Option<Self> {")
    w("        Self::ALL.iter().copied().find(|k| *k as u16 == v)")
    w("    }")
    w("")
    w("    /// 計画の名前 (`$HcomName`)")
    w("    pub fn name(self) -> &'static str {")
    w("        match self {")
    for name, v in coms:
        w(f"            CommandKind::{name} => {rust_str(names[v])},")
    w("        }")
    w("    }")
    w("")
    w("    /// 計画の値段 (`$HcomCost`)。負の値は食料で支払うことを表す。")
    w("    pub fn cost(self) -> i64 {")
    w("        match self {")
    for name, v in coms:
        w(f"            CommandKind::{name} => {costs[v]},")
    w("        }")
    w("    }")
    w("}")
    w("")
    by_value = {v: name for name, v in coms}
    lst = cfg["@HcomList"]
    w("/// 開発画面での計画の並び順 (`@HcomList`)")
    w(f"pub const COMMAND_LIST: [CommandKind; {len(lst)}] = [")
    for v in lst:
        w(f"    CommandKind::{by_value[v]},")
    w("];")
    w("")

    # ---- monsters ---------------------------------------------------------
    n = len(cfg["@HmonsterName"])
    w("/// 怪獣の定義 (`@HmonsterName` ほか)")
    w("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    w("pub struct MonsterSpec {")
    w("    pub name: &'static str,")
    w("    /// 最低体力 (`@HmonsterBHP`)")
    w("    pub base_hp: i64,")
    w("    /// 体力の幅 (`@HmonsterDHP`)")
    w("    pub hp_range: i64,")
    w("    /// 特殊能力 (`@HmonsterSpecial`)")
    w("    pub special: i64,")
    w("    /// 経験値 (`@HmonsterExp`)")
    w("    pub exp: i64,")
    w("    /// 死体の値段 (`@HmonsterValue`)")
    w("    pub value: i64,")
    w("    pub image: &'static str,")
    w("    /// 硬化中の画像 (`@HmonsterImage2`)。空文字列なら無し")
    w("    pub image_hardened: &'static str,")
    w("}")
    w("")
    w(f"pub const MONSTERS: [MonsterSpec; {n}] = [")
    for i in range(n):
        w("    MonsterSpec {")
        w(f"        name: {rust_str(cfg['@HmonsterName'][i])},")
        w(f"        base_hp: {cfg['@HmonsterBHP'][i]},")
        w(f"        hp_range: {cfg['@HmonsterDHP'][i]},")
        w(f"        special: {cfg['@HmonsterSpecial'][i]},")
        w(f"        exp: {cfg['@HmonsterExp'][i]},")
        w(f"        value: {cfg['@HmonsterValue'][i]},")
        w(f"        image: {rust_str(cfg['@HmonsterImage'][i])},")
        w(f"        image_hardened: {rust_str(cfg['@HmonsterImage2'][i])},")
        w("    },")
    w("];")
    w("")

    # ---- monuments / ships / prizes --------------------------------------
    def name_image_table(const, doc, names_key, images_key, extra=None):
        names_ = cfg[names_key]
        images_ = cfg[images_key]
        assert len(names_) == len(images_), const
        w(f"/// {doc}")
        if extra:
            w(f"pub const {const}: [(&str, &str, i64); {len(names_)}] = [")
            for a, b, c in zip(names_, images_, cfg[extra]):
                w(f"    ({rust_str(a)}, {rust_str(b)}, {c}),")
        else:
            w(f"pub const {const}: [(&str, &str); {len(names_)}] = [")
            for a, b in zip(names_, images_):
                w(f"    ({rust_str(a)}, {rust_str(b)}),")
        w("];")
        w("")

    name_image_table(
        "MONUMENTS", "記念碑 (名前, 画像) (`@HmonumentName`, `@HmonumentImage`)",
        "@HmonumentName", "@HmonumentImage",
    )
    name_image_table(
        "SHIPS", "船舶 (名前, 画像, 特殊能力) (`@HfuneName`, `@HfuneImage`, `@HfuneSpecial`)",
        "@HfuneName", "@HfuneImage", extra="@HfuneSpecial",
    )
    prizes = cfg["@Hprize"]
    w("/// 賞の名前 (`@Hprize`)")
    w(f"pub const PRIZE_NAMES: [&str; {len(prizes)}] = [")
    for p in prizes:
        w(f"    {rust_str(p)},")
    w("];")
    w("")
    w("/// ミサイル基地のレベルアップ経験値 (`@baseLevelUp`)")
    w(f"pub const BASE_LEVEL_UP: [i64; {len(cfg['@baseLevelUp'])}] = {cfg['@baseLevelUp']};")
    w("/// 海底基地のレベルアップ経験値 (`@sBaseLevelUp`)")
    w(f"pub const SBASE_LEVEL_UP: [i64; {len(cfg['@sBaseLevelUp'])}] = {cfg['@sBaseLevelUp']};")
    w(f"/// ミサイル基地の最大レベル (`$maxBaseLevel`)")
    w(f"pub const MAX_BASE_LEVEL: i64 = {cfg['$maxBaseLevel']};")
    w(f"/// 海底基地の最大レベル (`$maxSBaseLevel`)")
    w(f"pub const MAX_SBASE_LEVEL: i64 = {cfg['$maxSBaseLevel']};")
    w(f"/// 島主の家のランク境界 (`$HouseLevel1`..`$HouseLevel9`)")
    houses = [cfg[f"$HouseLevel{i}"] for i in range(1, 10)]
    w(f"pub const HOUSE_LEVELS: [i64; 9] = {houses};")

    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
