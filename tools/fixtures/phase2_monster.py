"""phase2-monster*: doEachHex の怪獣の分岐 (特殊能力・硬化・攻撃・移動・地雷) の
突き合わせ用データ。

rand が 0 と 0.5 に固定されるので、移動の向きは rand 0 なら右上 (方向 1)、rand 0.5 なら
下 (方向 4) に決まる。怪獣の能力が作るほかの系統の地形 (浅瀬・氷河・記念碑 93 など) が
ループの後の方のマスにできると、そのマスで Perl 版の未移植の分岐が動いてしまうので、
そうならない配置にしてある (右下の隅に置く、まわりを海にするなど)。

    python3 -I tools/fixtures/phase2_monster.py
    for f in phase2-monster phase2-monster-even phase2-monster-lords \
             phase2-monster-mascot phase2-monster-misc; do
        tools/perl-harness/run-harness.sh $f estimate,eachhex,estimate
    done
"""
import pathlib
